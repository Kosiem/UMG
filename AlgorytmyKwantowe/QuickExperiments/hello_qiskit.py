"""Qiskit and IBM Quantum Runtime experiments.

This file demonstrates two prototype experiments:
1. observable measurement for the Bell state (2 qubits),
2. correlation analysis for the GHZ state with n qubits.

Based on:
    https://quantum-computing.ibm.com/
"""

from __future__ import annotations

import os

from matplotlib import pyplot as plt
from qiskit import QuantumCircuit
from qiskit.quantum_info import SparsePauliOp
from qiskit.transpiler import generate_preset_pass_manager
from qiskit_ibm_runtime import QiskitRuntimeService
from qiskit_ibm_runtime.executor_estimator import Estimator
from qiskit_ibm_runtime.options_models import EstimatorOptions


def configure_runtime_service() -> QiskitRuntimeService:
    """Log in to IBM Quantum Runtime using environment variables.

    The QISKIT_IBM_TOKEN variable is the required access token for IBM Quantum,
    and QISKIT_IBM_INSTANCE is the instance name associated with the account.
    """
    token = os.getenv("QISKIT_IBM_TOKEN")
    instance = os.getenv("QISKIT_IBM_INSTANCE")

    if not token:
        raise RuntimeError(
            "Missing IBM Quantum token. Set the "
            "QISKIT_IBM_TOKEN environment variable."
        )

    # Save the account only when the required data has been provided.
    QiskitRuntimeService.save_account(
        token=token,
        instance=instance,
        set_as_default=True,
        overwrite=True,
    )

    return QiskitRuntimeService()


def create_bell_pair_circuit() -> QuantumCircuit:
    """Return the circuit that prepares the Bell state for two qubits.

    The Bell state |Φ+> = (|00> + |11>) / sqrt(2) is generated by applying H
    to qubit 0 and then CNOT from qubit 0 to 1.
    """
    qc = QuantumCircuit(2)
    qc.h(0)
    qc.cx(0, 1)
    return qc


def run_bell_pair_experiment(service: QiskitRuntimeService) -> None:
    """Run the Bell-state observable experiment.

    In practice, we measure different Pauli operators on the Bell circuit. This
    provides insight into qubit correlations and allows comparison with theory.
    """
    qc = create_bell_pair_circuit()

    # Different operators to measure in the Z and X bases.
    observables_labels = ["IZ", "IX", "ZI", "XI", "ZZ", "XX"]
    observables = [SparsePauliOp(label) for label in observables_labels]

    backend = service.least_busy(simulator=False, operational=True)

    # Map the circuit to the backend ISA and attach the operators
    # to the physical qubits available on the backend.
    pass_manager = generate_preset_pass_manager(
        backend=backend, optimization_level=1
    )
    isa_circuit = pass_manager.run(qc)

    # Qiskit Runtime experiments use transpiled circuits and
    # mapped observables.
    mapped_observables = [
        observable.apply_layout(isa_circuit.layout)
        for observable in observables
    ]

    estimator = Estimator(mode=backend)
    estimator.options.resilience_level = 1
    estimator.options.default_shots = 5000

    job = estimator.run([(isa_circuit, mapped_observables)])
    print(f">>> Job ID bell-pair: {job.job_id()}")

    result = job.result()[0]
    values = result["evs"]
    errors = result["stds"]

    # Plot expected values for each observable.
    plt.figure(figsize=(8, 5))
    plt.plot(observables_labels, values, "-o", color="tab:blue")
    plt.axhline(0, color="black", linewidth=0.8, linestyle="--")
    plt.xlabel("Observable")
    plt.ylabel("Expected value")
    plt.title("Bell state — expected values for different observables")
    plt.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.show()

    # Standard error values are useful for assessing measurement stability.
    print("Expected values:", values)
    print("Standard errors:", errors)


def create_ghz_state_circuit(n: int) -> QuantumCircuit:
    """Create the GHZ state for n qubits.

    The GHZ state for n qubits has the form:
        |GHZn> = (|0...0> + |1...1>) / sqrt(2).

    It is produced by applying H to the first qubit, followed by a CNOT chain:
    q0 -> q1 -> q2 -> ... -> q(n-1).
    """
    if isinstance(n, int) and n >= 2:
        qc = QuantumCircuit(n)
        qc.h(0)
        for qubit in range(n - 1):
            qc.cx(qubit, qubit + 1)
        return qc

    raise ValueError("n must be an integer greater than or equal to 2")


def run_ghz_experiment(
    service: QiskitRuntimeService, n_qubits: int = 100
) -> None:
    """Study GHZ coherence using Z_i Z_j operators.

    For the GHZ state, qubit correlations are strong. This experiment measures
    operators of the form Z_i Z_0 at different distances
    and compare the results to the baseline to see how quickly the correlation
    decays.
    """
    qc = create_ghz_state_circuit(n_qubits)

    # The first qubit in each Z_i Z_0 operator is the reference point.
    operators = [
        SparsePauliOp("Z" + "I" * i + "Z" + "I" * (n_qubits - 2 - i))
        for i in range(n_qubits - 1)
    ]

    backend = service.least_busy(
        simulator=False,
        operational=True,
        min_num_qubits=n_qubits,
    )

    pass_manager = generate_preset_pass_manager(
        backend=backend, optimization_level=1
    )
    isa_circuit = pass_manager.run(qc)
    mapped_operators = [
        op.apply_layout(isa_circuit.layout) for op in operators
    ]

    options = EstimatorOptions()
    options.resilience_level = 1
    options.dynamical_decoupling.enable = True
    options.dynamical_decoupling.sequence_type = "XY4"

    estimator = Estimator(mode=backend, options=options)
    job = estimator.run([(isa_circuit, mapped_operators)])
    print(f">>> Job ID ghz: {job.job_id()}")

    result = job.result()[0]
    values = result["evs"]
    data = list(range(1, len(operators) + 1))

    # Normalize with respect to the first point for a better shape comparison.
    normalized_values = [value / values[0] for value in values]

    plt.figure(figsize=(8, 5))
    plt.plot(
        data,
        normalized_values,
        marker="o",
        label=f"GHZ state ({n_qubits} qubits)",
    )
    plt.xlabel("Qubit distance")
    plt.ylabel(r"$\langle Z_i Z_0 \rangle / \langle Z_1 Z_0 \rangle$")
    plt.title("Correlation decay in the GHZ state")
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.tight_layout()
    plt.show()

    print("Normalized values:", normalized_values)


def main() -> None:
    """Main function that runs both experiments."""
    service = configure_runtime_service()

    # Experiment 1: Bell state and different observables.
    run_bell_pair_experiment(service)

    # Experiment 2: GHZ state and qubit correlations.
    run_ghz_experiment(service, n_qubits=100)


if __name__ == "__main__":
    main()
